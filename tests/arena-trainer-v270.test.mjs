import test from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {readFileSync,existsSync,mkdirSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const runner=path.join(root,'lab/arena/train.mjs');
const out=path.join(root,'reports','test-arena.json');
const replay=path.join(root,'reports','test-arena-replay.json');
test('authoritative training room runs all five real modes through bundled agent and server BotBrain',()=>{
 const r=spawnSync(process.execPath,[runner,'--seconds','4','--episodes','1','--bots','3','--replay',replay,'--out',out],{encoding:'utf8',timeout:90000});
 assert.equal(r.status,0,r.stderr?.slice(-1500));
 const data=JSON.parse(readFileSync(out,'utf8'));
 assert.deepEqual(new Set(data.results.map(v=>v.mode)),new Set(['tdm','snd','hp','br','zm']));
 assert.ok(data.results.every(v=>v.gameCode==='authoritative-server'));
 assert.ok(data.results.every(v=>v.agentCode==='bundled-page-agent'));
 assert.ok(data.results.every(v=>v.mapGeometryBoxes>0),'headless client must use the public arena collision geometry, not an empty placeholder');
 assert.ok(data.results.every(v=>v.errors===0),'extension should never fault during simulated room');
 const br=data.results.find(v=>v.mode==='br');
 assert.ok(br.distance>0,'autopilot must exit BR helicopter and navigate');
 const zm=data.results.find(v=>v.mode==='zm');
 assert.ok(zm.distance>0,'zombies mode should move');
 assert.ok(data.results.filter(v=>v.mode!=='zm').every(v=>v.bots>0),'official BotBrain players must be spawned');
 const recorded=JSON.parse(readFileSync(replay,'utf8'));
 assert.equal(recorded.records.length,5);
 assert.ok(recorded.records.every(r=>r.samples.length>0));
 assert.ok(recorded.records.every(r=>r.samples[0].enemies!==undefined));
});
